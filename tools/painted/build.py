"""Builds the painted art: renders every scene's layers with Blender, paints them and
writes the manifest the plug-in compiles in.

    python3 tools/painted/build.py [scene ...] [--scale 1.0] [--samples 48] [--jobs 3]   (default: every scene)

Renders go to build-art/render/<scene>; the finished layers to assets/painted/<scene>
(sky.jpg; far/mid/fog/near as .jpg colour + .png alpha); the manifest to
Source/UI/PaintedManifest.inc (layers, hotspots, landmarks, lights, moon).
"""
import argparse
import concurrent.futures as cf
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PY = sys.executable

def all_scenes():
    sys.path.insert(0, HERE)
    import scenes  # noqa: E402  (imports bpy: the registry of every scene)
    return sorted(scenes.REGISTRY)


def render(scene, scale, samples):
    out = os.path.join(ROOT, "build-art", "render", scene)
    subprocess.run([PY, os.path.join(HERE, "render.py"), scene, out, "--scale", str(scale), "--samples", str(samples)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return out


def paint(scene):
    src = os.path.join(ROOT, "build-art", "render", scene)
    dst = os.path.join(ROOT, "assets", "painted", scene)
    prev = os.path.join(ROOT, "build-art", "preview", scene.replace("/", "_") + ".jpg")
    os.makedirs(os.path.dirname(prev), exist_ok=True)
    subprocess.run([PY, os.path.join(HERE, "paint.py"), src, dst, "--preview", prev], check=True)
    return scene


KIND = {"hotspot": 0, "landmark": 1, "fire": 2, "window": 3, "lava": 4, "candle": 5, "glint": 6, "eyes": 7}


def manifest():
    """Writes Source/UI/PaintedManifest.inc from every assets/painted/**/scene.json."""
    base = os.path.join(ROOT, "assets", "painted")
    scenes = []
    for dirpath, _, files in os.walk(base):
        if "scene.json" in files:
            scenes.append(json.load(open(os.path.join(dirpath, "scene.json"))))
    scenes.sort(key=lambda s: s["scene"])
    lines = ["// Generated by tools/painted/build.py: do not edit. The painted scenes, their",
             "// depth layers and anchors (virtual 960 x 560 coordinates).",
             "// Anchor kinds: 0 hotspot (value = sub-location), 1 landmark (value = location),",
             "// 2 fire, 3 window, 4 lava, 5 candle, 6 glint, 7 eyes (value = radius).", ""]
    for i, s in enumerate(scenes):
        anchors = []
        for a in s["anchors"]:
            kind = KIND[a["kind"]]
            value = a.get("sub", a.get("index", a.get("radius", 0)))
            anchors.append(f'{{ {kind}, {a["x"]:.1f}f, {a["y"]:.1f}f, {float(value):.1f}f }}')
        lines.append(f'static const PaintedAnchor anchors{i}[] = {{ ' + ", ".join(anchors) + " };")
    lines.append("")
    lines.append("static const PaintedScene paintedScenes[] = {")
    for i, s in enumerate(scenes):
        layers = "|".join(s["layers"])
        m = s.get("moon", [0, 0, 0])
        lines.append(f'    {{ "{s["scene"]}", "{layers}", {{ {m[0]:.1f}f, {m[1]:.1f}f, {m[2]:.1f}f }}, anchors{i}, {len(s["anchors"])} }},')
    lines.append("};")
    path = os.path.join(ROOT, "Source", "UI", "PaintedManifest.inc")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("manifest:", len(scenes), "scenes ->", os.path.relpath(path, ROOT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scenes", nargs="*")
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--samples", type=int, default=48)
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--manifest-only", action="store_true")
    args = ap.parse_args()
    if not args.manifest_only:
        scenes = args.scenes or all_scenes()
        # Cycles uses every core, so scenes render one after another; painting (mostly
        # single-threaded numpy) runs in parallel with the next renders.
        with cf.ProcessPoolExecutor(max_workers=args.jobs) as pool:
            futures = []
            for s in scenes:
                render(s, args.scale, args.samples)
                print("rendered", s, flush=True)
                futures.append(pool.submit(paint, s))
            for f in cf.as_completed(futures):
                print("painted", f.result(), flush=True)
    manifest()


if __name__ == "__main__":
    main()
